#!/usr/bin/env python3
"""Generate COM vtable method-name tables from the mingw-w64 headers (exact slot order)."""
import re, sys, os
INC = "/usr/x86_64-w64-mingw32/include"
HEADERS = ["d3dcommon.h", "d3d11.h", "d3d11_1.h", "d3d11_2.h", "d3d11_3.h", "dxgi.h", "dxgi1_2.h", "dxgi1_3.h", "dxgi1_4.h", "d3d12.h"]
out = {}
iids = {}
bases = {}
for h in HEADERS:
    path = os.path.join(INC, h)
    if not os.path.exists(path):
        continue
    src = open(path, encoding="utf-8", errors="replace").read()
    for m in re.finditer(r'MIDL_INTERFACE\("([0-9a-fA-F-]{36})"\)\s*(\w+)\s*(?::\s*public\s+(\w+))?', src):
        iids[m.group(1).lower()] = m.group(2)
        if m.group(3):
            bases[m.group(2)] = m.group(3)
    for m in re.finditer(r"typedef struct (\w+)Vtbl \{(.*?)\n\} \1Vtbl;", src, re.S):
        name, body = m.group(1), m.group(2)
        body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)
        methods = re.findall(r"\(\s*STDMETHODCALLTYPE\s*\*\s*(\w+)\s*\)", body)
        if methods and name not in out:
            out[name] = methods
lines = ["// @generated by tools/gen_vtables.py from the mingw-w64 headers. Do not edit.", "",
         "pub fn methods(interface: &str) -> Option<&'static [&'static str]> {", "    Some(match interface {"]
for name in sorted(out):
    lines.append(f'        "{name}" => &[{", ".join(chr(34)+m+chr(34) for m in out[name])}],')
lines += ["        _ => return None,", "    })", "}", ""]
lines += ["/// Interface name for an IID string (lower-case, hyphenated).", "pub fn iid_name(iid: &str) -> Option<&'static str> {", "    Some(match iid {"]
for g in sorted(iids):
    lines.append(f'        "{g}" => "{iids[g]}",')
lines += ["        _ => return None,", "    })", "}", ""]
lines += ["/// Direct base interface (COM inheritance), if known.", "pub fn base_of(interface: &str) -> Option<&'static str> {", "    Some(match interface {"]
for n in sorted(bases):
    lines.append(f'        "{n}" => "{bases[n]}",')
lines += ["        _ => return None,", "    })", "}", ""]
dest = os.path.join(os.path.dirname(__file__), "..", "crates", "anywasm-rt", "src", "hle", "vtables.rs")
open(dest, "w").write("\n".join(lines))
print(f"{len(out)} interfaces")
for n in ("ID3D11Device", "ID3D11DeviceContext", "IDXGISwapChain", "IDXGIFactory"):
    print(n, len(out[n]), out[n][:5], "...")
