// Compile the HLSL used by the D3D11 fixtures to DXBC and emit C headers.
// Usage: node fixtures/gen_d3d_shaders.mjs   (uses the vendored vkd3d-shader WASM compiler)
import { writeFileSync } from 'node:fs';
import { ShaderTool } from '../web/shaders.js';

const t = new ShaderTool();
await t.init();
const emit = (file, name, bytes) => {
  const rows = [];
  for (let i = 0; i < bytes.length; i += 16) rows.push('    ' + [...bytes.slice(i, i + 16)].map((b) => '0x' + b.toString(16).padStart(2, '0')).join(', ') + ',');
  return `static const unsigned char ${name}[] = {\n${rows.join('\n')}\n};\n`;
};

const triangle = `
struct VSIn { float3 pos : POSITION; float4 col : COLOR; };
struct PSIn { float4 pos : SV_Position; float4 col : COLOR; };
cbuffer Frame : register(b0) { float4 tint; };
PSIn vs_main(VSIn i) { PSIn o; o.pos = float4(i.pos, 1.0); o.col = i.col * tint; return o; }
float4 ps_main(PSIn i) : SV_Target { return i.col; }
`;
let h = '// @generated by fixtures/gen_d3d_shaders.mjs (HLSL -> DXBC via vkd3d-shader). Do not edit.\n';
h += emit('t', 'tri_vs', t.compileHlsl(triangle, 'vs_main', 'vs_5_0', 'triangle.hlsl'));
h += emit('t', 'tri_ps', t.compileHlsl(triangle, 'ps_main', 'ps_5_0', 'triangle.hlsl'));
writeFileSync(new URL('./shaders_triangle.h', import.meta.url), h);

const textured = `
cbuffer Frame : register(b0) { float4x4 mvp; };
Texture2D tex : register(t0);
SamplerState smp : register(s0);
struct VSIn { float3 pos : POSITION; float2 uv : TEXCOORD0; };
struct PSIn { float4 pos : SV_Position; float2 uv : TEXCOORD0; };
PSIn vs_main(VSIn i) { PSIn o; o.pos = mul(mvp, float4(i.pos, 1.0)); o.uv = i.uv; return o; }
float4 ps_main(PSIn i) : SV_Target { return tex.Sample(smp, i.uv); }
`;
let h2 = '// @generated by fixtures/gen_d3d_shaders.mjs. Do not edit.\n';
h2 += emit('x', 'tex_vs', t.compileHlsl(textured, 'vs_main', 'vs_5_0', 'textured.hlsl'));
h2 += emit('x', 'tex_ps', t.compileHlsl(textured, 'ps_main', 'ps_5_0', 'textured.hlsl'));
writeFileSync(new URL('./shaders_textured.h', import.meta.url), h2);
console.log('wrote fixtures/shaders_triangle.h, fixtures/shaders_textured.h');
